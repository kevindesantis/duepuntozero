function getLangFromUrl(){
  const lang = new URLSearchParams(location.search).get('lang');
  return ['it','en','es'].includes(lang) ? lang : null;
}
function getLang(){
  return getLangFromUrl() || localStorage.getItem(LANG_KEY) || 'it';
}
function t(key){
  const lang = getLang();
  return I18N[lang]?.ui?.[key] || I18N.it.ui[key] || key;
}
function setLang(lang){
  if(!['it','en','es'].includes(lang)) return;
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang;
  translateStaticPage();
  updateLangButtons();
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}
function updateLangButtons(){
  const lang = getLang();
  document.querySelectorAll('[data-lang]').forEach(btn=>{
    btn.classList.toggle('active', btn.dataset.lang === lang);
    btn.setAttribute('aria-pressed', btn.dataset.lang === lang ? 'true' : 'false');
  });
}
function initLanguageSwitcher(){
  document.documentElement.lang = getLang();
  document.querySelectorAll('[data-lang]').forEach(btn=>{
    btn.addEventListener('click', ()=>setLang(btn.dataset.lang));
  });
  translateStaticPage();
  updateLangButtons();
}
function translateStaticPage(){
  document.documentElement.lang = getLang();
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
}
function categoryLabel(category){
  const lang = getLang();
  if(lang === 'it') return category;

  // Per le categorie create dal gestore su Supabase usa prima le traduzioni salvate nel database.
  const full = window.DPZ_CATEGORIES_FULL || [];
  const row = full.find(c => c.name_it === category || c.id === category);
  if(row){
    const direct = row[`name_${lang}`];
    if(direct) return direct;
  }

  return CATEGORY_TRANSLATIONS[lang]?.[category] || category;
}
function itemLabel(item, field){
  const lang = getLang();

  // Se i dati arrivano da Supabase, usiamo prima le colonne tradotte del database.
  if(lang !== 'it'){
    const direct = item[`${field}_${lang}`];
    if(direct) return direct;
  }else{
    const directIt = item[`${field}_it`];
    if(directIt) return directIt;
  }

  if(lang === 'it') return item[field] || '';
  const arr = ITEM_TRANSLATIONS[lang]?.[item.id];
  if(!arr) return item[field] || '';
  if(field === 'name') return arr[0] || item.name || '';
  if(field === 'description') return arr[1] || item.description || '';
  if(field === 'ingredients') return arr[2] || item.ingredients || '';
  return item[field] || '';
}
function allergenLabel(data, id, short=false){
  const lang = getLang();
  const a = data.allergens.find(x=>Number(x.id)===Number(id));

  if(lang === 'it'){
    return short ? (a?.short || id) : (a?.name || `Allergene ${id}`);
  }

  // Prima prova i valori arrivati da Supabase.
  if(a){
    const direct = short ? a[`short_${lang}`] : a[`name_${lang}`];
    if(direct) return direct;
  }

  const arr = ALLERGEN_TRANSLATIONS[lang]?.[id];
  return arr ? (short ? arr[1] : arr[0]) : `Allergen ${id}`;
}
